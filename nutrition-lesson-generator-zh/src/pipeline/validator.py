"""证据/安全质量验证器 —— 中文版"""

from typing import List, Tuple
from src.schemas.lesson import 课程规范, 课件页面


def 验证课程(课程: 课程规范) -> Tuple[bool, List[str]]:
    """验证课程规范和安全性，返回 (是否通过, 问题列表)"""
    问题: List[str] = []

    # 1. 页面完整性
    if not 课程.页面列表:
        问题.append("课程页面为空")
    if len(课程.页面列表) < 5:
        问题.append(f"页面数量不足：{len(课程.页面列表)}（建议 > 5）")

    # 2. 引用完整性
    if not 课程.引用列表:
        问题.append("引用列表为空")

    # 3. 安全关键词检查 —— 禁止疾病治疗语言
    #    注：参考文献页底部的标准免责声明（含"诊断和治疗建议"）为合法模板，跳过该页检查
    禁止词 = ["治疗", "治愈", "处方", "用药", "剂量", "剂量推荐", "用药方案", "替代医疗"]
    for 页面 in 课程.页面列表:
        if 页面.页面类型 == "参考文献":
            continue
        for 词 in 禁止词:
            if 词 in 页面.正文 or 词 in 页面.讲稿:
                问题.append(f"第{页面.页码}页发现禁止词'{词}'")

    # 4. 特殊人群安全门（规则9）—— 涉及脆弱人群须标注专业指导
    #    参考文献页免责声明含"专业医疗建议"但非受众指导语境，跳过
    特殊人群词 = ["孕妇", "乳母", "哺乳期", "婴幼儿", "儿童", "青少年",
                  "老年人", "老人", "肝肾", "肾病", "肝病", "慢性病患者"]
    指导标注词 = ["医师指导下", "注册营养师指导", "专业指导下", "咨询医生", "咨询营养师", "医师指导下应用"]
    for 页面 in 课程.页面列表:
        if 页面.页面类型 == "参考文献":
            continue
        文本 = 页面.正文 + " " + 页面.讲稿
        if any(w in 文本 for w in 特殊人群词):
            if not any(g in 文本 for g in 指导标注词):
                问题.append(f"第{页面.页码}页涉及特殊人群但未标注'需在医师/注册营养师指导下应用'")

    # 5. 进食障碍 / 体重管理羞耻化语言检查（规则10）
    羞耻词 = ["胖子", "肥婆", "懒", "贪吃", "意志力差", "没毅力", "丑", "丢人",
              "羞耻", "自制力差", "管不住嘴", "胖就是", "瘦才"]
    for 页面 in 课程.页面列表:
        if 页面.页面类型 == "参考文献":
            continue
        文本 = 页面.正文 + " " + 页面.讲稿
        for 词 in 羞耻词:
            if 词 in 文本:
                问题.append(f"第{页面.页码}页出现疑似羞耻化语言'{词}'，请改用中性表述")

    # 6. 证据声明与引用的对应性（引用也可直接出现在幻灯片上）
    声明中引用 = set()
    for es in 课程.证据声明列表:
        for rid in es.引用:
            声明中引用.add(rid)
    for 页面 in 课程.页面列表:
        for rid in 页面.引用编号:
            声明中引用.add(rid)
    引用编号集 = set(r.编号 for r in 课程.引用列表)
    孤立引用 = 引用编号集 - 声明中引用
    if 孤立引用:
        问题.append(f"以下引用未被任何证据声明或幻灯片使用：{孤立引用}")

    # 7. 页面类型分布检查
    类型列表 = [p.页面类型 for p in 课程.页面列表]
    for 必需类型 in ["封面", "内容", "参考文献"]:
        if 必需类型 not in 类型列表:
            问题.append(f"缺少必需页面类型：{必需类型}")

    通过 = len(问题) == 0
    return 通过, 问题
