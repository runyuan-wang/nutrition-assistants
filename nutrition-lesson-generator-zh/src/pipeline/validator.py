"""证据/安全质量验证器 —— 中文版"""

from typing import List, Tuple
from src.schemas.lesson import 课程规范, 课件页面


def 验证课程(课程: 课程规范) -> Tuple[bool, List[str]]:
    """验证课程规范和安全性，返回 (是否通过, 问题列表)"""
    问题: List[str] = []

    # 1. 页面完整性
    if not 课程.页面列表:
        问题.append("课程页面为空")
    if len(课程.页面列表) < 5:
        问题.append(f"页面数量不足：{len(课程.页面列表)}（建议 > 5）")

    # 2. 引用完整性
    if not 课程.引用列表:
        问题.append("引用列表为空")

    # 3. 安全关键词检查 —— 禁止疾病治疗语言
    禁止词 = ["治疗", "治愈", "处方", "用药", "剂量", "剂量推荐", "用药方案", "替代医疗"]
    for 页面 in 课程.页面列表:
        for 词 in 禁止词:
            if 词 in 页面.正文 or 词 in 页面.讲稿:
                问题.append(f"第{页面.页码}页发现禁止词'{词}'")

    # 4. 证据声明与引用的对应性
    声明中引用 = set()
    for es in 课程.证据声明列表:
        for rid in es.引用:
            声明中引用.add(rid)
    引用编号集 = set(r.编号 for r in 课程.引用列表)
    孤立引用 = 引用编号集 - 声明中引用
    if 孤立引用:
        问题.append(f"以下引用未被任何证据声明使用：{孤立引用}")

    # 5. 页面类型分布检查
    类型列表 = [p.页面类型 for p in 课程.页面列表]
    for 必需类型 in ["封面", "内容", "参考文献"]:
        if 必需类型 not in 类型列表:
            问题.append(f"缺少必需页面类型：{必需类型}")

    通过 = len(问题) == 0
    return 通过, 问题
