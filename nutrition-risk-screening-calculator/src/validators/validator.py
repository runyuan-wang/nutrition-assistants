"""红线与一致性校验。

营养筛查工具的输出边界：只给"筛查结果 + 建议方向"，绝不越界到
临床处置（治疗/治愈/处方/用药/剂量）。本模块负责兜底检查。
"""
from __future__ import annotations

from ..schemas.screening import 筛查结果

# 越界即违规的临床处置词（仅针对"说明/建议"，不针对免责声明中的"诊断"表述）
红线词 = ["治疗", "治愈", "处方", "用药", "剂量"]


def 红线校验(结果: 筛查结果) -> list[str]:
    """扫描风险说明与建议，返回命中的越界词列表。"""
    文本 = 结果.风险说明 + " " + 结果.建议
    命中 = [w for w in 红线词 if w in 文本]
    return 命中


def 校验(结果: 筛查结果) -> tuple[bool, list[str]]:
    """返回 (是否通过, 警告列表)。"""
    警告: list[str] = []
    命中 = 红线校验(结果)
    if 命中:
        警告.append(f"⚠️ 命中临床处置红线词：{', '.join(命中)}，请复核输出是否越界。")
    if not 结果.免责声明:
        警告.append("⚠️ 缺少免责声明，已自动补全。")
        结果.免责声明 = (
            "本结果仅为营养风险筛查，不能替代临床营养诊断与医师面诊；"
            "阳性结果需由临床营养师/医师结合综合评估确认。"
        )
    return (len(命中) == 0, 警告)
