"""STAMP 儿科营养不良评估筛查工具（2–17 岁，中国国家临床营养质控中心 2021 推荐）。

3 维度（疾病风险 0/2/3 + 膳食摄入 0/2/3 + 人体测量 0/1/3），满分 9。
≤1 低危 / 2–3 中危 / ≥4 高危。
参考文献：McCarthy H, et al. J Hum Nutr Diet. 2012;25(3):277-86.
国家临床营养质控中心《提高患者入院 24 小时内营养风险筛查率核心策略》2021。
"""
from __future__ import annotations

from ..schemas.screening import STAMP输入, 筛查结果, 筛查工具, 风险等级


def 计算(i: STAMP输入) -> 筛查结果:
    total = i.疾病风险评分 + i.膳食摄入评分 + i.人体测量评分

    if total <= 1:
        level = 风险等级.低危
    elif total <= 3:
        level = 风险等级.中危
    else:
        level = 风险等级.高危

    note = f"STAMP 总分 {total}/9（疾病风险={i.疾病风险评分}, 膳食摄入={i.膳食摄入评分}, 人体测量={i.人体测量评分}）。"
    if level == 风险等级.高危:
        note += "高危：需进行营养诊疗，请通知营养科医师会诊。"
        advice = "高危——转营养科，启动全面营养评估与干预。"
    elif level == 风险等级.中危:
        note += "中危：须连续 3 天监测营养摄入状况，3 天后复筛。"
        advice = "中危——营养监测，连续 3 天记录饮食，3 天后重新评分。"
    else:
        note += "低危：暂无营养风险。"
        advice = "低危——继续常规临床治疗，每周复筛。"

    return 筛查结果(
        工具=筛查工具.STAMP,
        总分=total,
        维度分={
            "疾病风险评分": i.疾病风险评分,
            "膳食摄入评分": i.膳食摄入评分,
            "人体测量评分": i.人体测量评分,
        },
        风险等级=level,
        风险说明=note,
        建议=advice,
    )
